/**
 * Returns brand badge styling and corresponding icon component based on channel type.
 */
export function getChannelBadge(type: string = "") {
  const normalized = type.toLowerCase().trim();

  switch (normalized) {
    case "whatsapp":
      return {
        badgeClass: "border-[#25d366]/30 bg-[#25d366]/[0.08] text-[#25d366]",
        Icon: Whatsapp,
      };
    case "linkedin":
      return {
        badgeClass: "border-[#0077b5]/30 bg-[#0077b5]/[0.08] text-[#0077b5]",
        Icon: Linkedin,
      };
    case "github":
      return {
        badgeClass: "border-white/25 bg-white/[0.08] text-white",
        Icon: Github,
      };
    case "x":
    case "twitter":
      return {
        badgeClass: "border-white/30 bg-white/[0.1] text-white",
        Icon: XTwitter,
      };
    case "instagram":
      return {
        badgeClass: "border-[#E1306C]/30 bg-[#E1306C]/[0.1] text-[#E1306C]",
        Icon: Instagram,
      };
    case "pinterest":
      return {
        badgeClass: "border-[#E60023]/30 bg-[#E60023]/[0.1] text-[#E60023]",
        Icon: Pinterest,
      };
    case "youtube":
      return {
        badgeClass: "border-[#FF0000]/30 bg-[#FF0000]/[0.1] text-[#FF0000]",
        Icon: Youtube,
      };
    case "email":
    case "mail":
      return {
        badgeClass: "border-white/30 bg-white/[0.1] text-white",
        Icon: MailIcon,
      };
    default:
      return {
        badgeClass: "border-white/20 bg-white/[0.06] text-white/90",
        Icon: GenericLink,
      };
  }
}
